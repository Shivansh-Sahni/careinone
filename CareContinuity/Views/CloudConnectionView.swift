import SwiftUI
import CareCore

struct CloudConnectionView: View {
    @Environment(AppStore.self) private var store
    @State private var endpoint = ""
    @State private var token = ""
    @State private var configuration: GatewayConfiguration?
    @State private var result: String?
    @State private var failure: String?
    @State private var task: Task<Void, Never>?
    @State private var running = false
    @State private var generation = UUID()
    var body: some View {
        Form {
            Section {
                Label("Optional cloud analysis", systemImage: "cloud").font(.headline)
                Text("Connect your CareContinuity gateway to use OpenAI, Kimi, or another compatible model. Capture, local text recognition, review, and your saved care remain available without it.")
            }
            Section("1 · Connect your gateway") {
                TextField("Gateway HTTPS URL", text: $endpoint).keyboardType(.URL).textInputAutocapitalization(.never).autocorrectionDisabled().accessibilityIdentifier("gateway-url")
                SecureField("Gateway access token", text: $token).textInputAutocapitalization(.never).autocorrectionDisabled().accessibilityIdentifier("gateway-token")
                Text("Use the access token generated by the server setup command. The OpenAI or Kimi API key belongs only on your server.").font(.caption).foregroundStyle(.secondary)
                Button("Check gateway configuration") { check(runModel: false) }.disabled(running)
            }
            if let configuration {
                Section("2 · Know where analysis runs") {
                    provider(configuration.providers.primary, title: "Primary model")
                    if let fallback = configuration.providers.fallback { provider(fallback, title: "Fallback model") }
                    Text("Up to \(configuration.maxSourceCharacters.formatted()) characters per source. Your server operator controls this limit.").font(.caption)
                    Text(configuration.patientContentStored ? "This gateway reports that it stores patient content. Review its policies before enabling cloud analysis." : "This gateway reports no patient-content storage. Model-provider retention is separate; review the terms of every configured provider.").font(.caption).foregroundStyle(.secondary)
                    Button("Test with synthetic text") { check(runModel: true) }.disabled(running)
                    Text("Sends one fixed, invented follow-up sentence. No saved patient information is sent. This uses a small amount of your provider’s API quota.").font(.caption).foregroundStyle(.secondary)
                }
            }
            if running { Section { ProgressView("Checking connection…"); Button("Cancel", role: .cancel) { invalidate() } } }
            if let result { Section { Label(result, systemImage: "checkmark.circle").foregroundStyle(Theme.accent).accessibilityIdentifier("gateway-result") } }
            if let failure { Section { Label(failure, systemImage: "exclamationmark.triangle").foregroundStyle(.secondary).accessibilityIdentifier("gateway-error") } }
            Section("3 · Save the connection") {
                Button("Save connection", systemImage: "key") {
                    saveConnection(allowCloud: false)
                }.disabled(running)
                if configuration != nil {
                    Text("Allow your source text and event date to be sent to this gateway and the primary or fallback model shown above. Original photos, files, and audio stay on this iPhone. Model output remains a proposal until you review it.").font(.subheadline)
                    Button("Allow cloud analysis with these models") { saveConnection(allowCloud: true) }.disabled(running)
                }
                Text("Saving a connection alone leaves cloud analysis off. You can turn consent off at any time in Settings.").font(.caption).foregroundStyle(.secondary)
            }
            Section("Server setup") {
                Text("On the computer hosting your gateway, run:").font(.subheadline)
                Text("python -m backend.configure").font(.system(.subheadline, design: .monospaced)).textSelection(.enabled)
                Text("Choose a provider and a model available in your account. Deploy the gateway behind HTTPS. Configure provider spending limits in its account dashboard.").font(.caption).foregroundStyle(.secondary)
            }
        }.navigationTitle("Cloud connection").navigationBarTitleDisplayMode(.inline)
            .onAppear { let saved = KeychainStore.backend; endpoint = saved.endpoint; token = saved.token }
            .onChange(of: endpoint) { invalidate(); configuration = nil; result = nil; failure = nil }
            .onChange(of: token) { invalidate(); configuration = nil; result = nil; failure = nil }
            .onDisappear { invalidate() }
    }
    private func provider(_ value: GatewayProviderInfo, title: String) -> some View {
        VStack(alignment: .leading, spacing: 4) {
            Text(title).font(.caption).foregroundStyle(.secondary)
            Text(value.model).font(.headline)
            Text(value.host).font(.caption).textSelection(.enabled)
            Text(value.adapter == "mock" ? "Development mock · does not perform clinical extraction" : "\(value.adapter.capitalized) · maximum \(value.maxOutputTokens.formatted()) output tokens per chunk").font(.caption)
        }
    }
    private func invalidate() { generation = UUID(); task?.cancel(); task = nil; running = false }
    private func saveConnection(allowCloud: Bool) {
        do {
            let cleaned = endpoint.trimmingCharacters(in: .whitespacesAndNewlines)
            _ = try GatewayClient.validate(endpoint: cleaned, token: token)
            // Disable old consent before changing the destination, even if Keychain saving fails.
            var profile = store.state.profile
            profile.cloudConsent = false; profile.cloudConsentAt = nil; profile.cloudProviderConfigurationID = nil
            guard store.saveProfile(profile) else { return }
            try KeychainStore.saveBackend(endpoint: cleaned, token: token)
            if allowCloud, let configuration {
                profile.cloudConsent = true; profile.cloudConsentAt = Date(); profile.cloudProviderConfigurationID = configuration.configurationID
                guard store.saveProfile(profile) else { return }
            }
            result = allowCloud ? "Cloud analysis allowed for these configured models. New proposals still require review." : "Connection saved in Keychain. Cloud analysis is off."
            failure = nil
        } catch { failure = error.localizedDescription }
    }
    private func check(runModel: Bool) {
        invalidate(); failure = nil; result = nil
        do {
            let url = try GatewayClient.validate(endpoint: endpoint.trimmingCharacters(in: .whitespacesAndNewlines), token: token)
            let client = GatewayClient(baseURL: url, token: token); let run = generation; running = true
            task = Task {
                defer { if generation == run { running = false; task = nil } }
                do {
                    if runModel {
                        let response = try await client.check(); try Task.checkCancellation()
                        guard generation == run else { return }
                        result = "Synthetic check passed using the \(response.route) model. No patient data was sent."
                    } else {
                        let response = try await client.configuration(); try Task.checkCancellation()
                        guard generation == run else { return }
                        configuration = response; result = "Gateway address and access token verified. The model has not been tested yet."
                    }
                } catch is CancellationError { } catch { if generation == run { failure = error.localizedDescription } }
            }
        } catch { failure = error.localizedDescription }
    }
}
